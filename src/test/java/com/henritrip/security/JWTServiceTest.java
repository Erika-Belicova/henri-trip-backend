package com.henritrip.security;

import com.henritrip.configuration.JwtProperties;
import com.henritrip.exception.JwtGenerationException;
import com.henritrip.model.entity.User;
import com.henritrip.model.enums.UserRole;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.security.core.Authentication;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.security.oauth2.jwt.JwtClaimsSet;
import org.springframework.security.oauth2.jwt.JwtEncoder;
import org.springframework.security.oauth2.jwt.JwtEncoderParameters;
import org.springframework.security.oauth2.jwt.JwtEncodingException;

import java.time.Instant;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

class JWTServiceTest {

    private JWTService jwtService;
    private JwtEncoder jwtEncoder;
    private JwtProperties jwtProperties;
    private Authentication authentication;

    @BeforeEach
    void setUp() {
        jwtEncoder = mock(JwtEncoder.class);
        jwtProperties = mock(JwtProperties.class);
        authentication = mock(Authentication.class);

        // configure a predictable user and token duration
        User user = new User();
        user.setId(1L);
        user.setEmail("user@example.com");
        user.setRole(UserRole.USER);

        when(authentication.getPrincipal())
                .thenReturn(new CustomUserDetails(user));

        when(jwtProperties.getAccessTokenDuration())
                .thenReturn(900000L);

        jwtService = new JWTService(jwtEncoder, jwtProperties);
    }

    @Test
    void generateAccessTokenShouldReturnTokenWithExpectedClaims() {
        // arrange: configure the encoder to return a generated token
        when(jwtEncoder.encode(any(JwtEncoderParameters.class)))
                .thenReturn(Jwt.withTokenValue("generated-token")
                        .header("alg", "HS256")
                        .claim("sub", "1")
                        .claim("role", "ROLE_USER")
                        .build());

        // capture the claims passed to the encoder for verification
        ArgumentCaptor<JwtEncoderParameters> captor =
                ArgumentCaptor.forClass(JwtEncoderParameters.class);

        // act: generate an access token for the authenticated user
        String token = jwtService.generateAccessToken(authentication);

        // assert: verify the returned token
        assertEquals("generated-token", token);

        // verify the claims generated by the service before encoding
        verify(jwtEncoder).encode(captor.capture());

        JwtClaimsSet claims = captor.getValue().getClaims();

        assertEquals("henri-trip", claims.getClaims().get("iss"));
        assertEquals("1", claims.getClaims().get("sub"));
        assertEquals("ROLE_USER", claims.getClaims().get("role"));

        // verify that the token has an issue time and the configured expiration
        Instant issuedAt = claims.getIssuedAt();
        Instant expiresAt = claims.getExpiresAt();

        assertNotNull(issuedAt);
        assertNotNull(expiresAt);
        assertEquals(900000L, expiresAt.toEpochMilli() - issuedAt.toEpochMilli());
    }

    @Test
    void generateAccessTokenShouldThrowExceptionWhenEncodingFails() {
        // arrange: simulate a JWT encoding failure
        when(jwtEncoder.encode(any(JwtEncoderParameters.class)))
                .thenThrow(new JwtEncodingException("Encoding failed"));

        // act & assert: verify that the encoding failure is wrapped in JwtGenerationException
        JwtGenerationException exception = assertThrows(
                JwtGenerationException.class,
                () -> jwtService.generateAccessToken(authentication)
        );

        assertEquals("Token generation failed.", exception.getMessage());
    }

}
